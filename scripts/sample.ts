import { promises as fs } from 'node:fs';
import path from 'node:path';
import YAML from 'yaml';
import { Vault } from '../packages/core/vault.js';
import { SearchEngine } from '../packages/search-files/index.js';
import { IntelligenceEngine } from '../packages/intelligence/index.js';
import { SyntheticFixtureModel } from '../fixtures/model.js';

const root = path.resolve(process.argv[2] ?? 'examples/sample-vault');
const vault = new Vault(root);
await vault.init({ sqlite: false });
if (!(await vault.listWorkspaces()).some(w => w.id === 'research')) await vault.createWorkspace('research', 'Synthetic agent research workspace', { 'sample-agent': ['read', 'write'] });
if (!(await vault.listCollections('research')).some(c => c.id === 'retrieval-study')) await vault.createCollection('research', 'retrieval-study', 'Synthetic study');
const scope = { type: 'workspace' as const, workspaceId: 'research', collectionId: 'retrieval-study' };
await vault.put({ scope, kind: 'note', title: '[SYNTHETIC] Initial retrieval observations', body: '# Retrieval observations\n\nLexical search is available without SQLite. All fixtures are synthetic.', tags: ['retrieval'], idempotencyKey: 'sample:retrieval' });
const python = await vault.put({ scope: { type: 'global', area: 'wiki' }, kind: 'fact', title: '[SYNTHETIC] Python API capability', body: 'Synthetic actor can write a Python HTTP API returning structured JSON.', tags: ['python'], metadata: { synthetic: true, domain: 'python-api' }, idempotencyKey: 'sample:python' });
const javascript = await vault.put({ scope: { type: 'global', area: 'wiki' }, kind: 'fact', title: '[SYNTHETIC] JavaScript UI capability', body: 'Synthetic actor can write a JavaScript browser interface consuming JSON.', tags: ['javascript'], metadata: { synthetic: true, domain: 'javascript-ui' }, idempotencyKey: 'sample:javascript' });
await vault.put({ scope: { type: 'global', area: 'profile' }, kind: 'note', title: '[SYNTHETIC] Explicit goal', body: 'Build a useful research notebook.', metadata: { synthetic: true, explicitPreference: true, profileRole: 'explicit' }, idempotencyKey: 'sample:goal' });
const sourceFile = path.resolve('fixtures/source.md');
await fs.writeFile(sourceFile, '# Synthetic source\n\nA Markdown vault can preserve revisions while serving agent knowledge.\n');
const source = await vault.ingest(sourceFile, { type: 'global', area: 'wiki' });
const config = await vault.config();
config.dream.enabled = true;
config.model.provider = 'synthetic-fixture-not-an-llm';
await fs.writeFile(path.join(root, 'mdb.yaml'), YAML.stringify(config));
const engine = new IntelligenceEngine(vault, new SyntheticFixtureModel());
await engine.enqueue('wiki', { scope: { type: 'global', area: 'wiki' }, objectIds: [source.id] });
await engine.run({ limit: 5 });
await engine.enqueue('dream', { scope: { type: 'global', area: 'discoveries' }, objectIds: [python.id, javascript.id], goals: 'Build a useful research notebook.', mode: 'micro' });
await engine.run({ limit: 5 });
for (const proposal of await engine.proposals()) if (proposal.status === 'pending') await engine.review(proposal.id, true, 'Explicitly accepted synthetic demonstration fixture; not factual model synthesis');
await new SearchEngine(vault).rebuild();
const result = await vault.verify();
if (!result.ok) throw new Error(JSON.stringify(result));
console.log(JSON.stringify({ root, synthetic: true, objects: (await vault.listDocuments()).length, verification: result }, null, 2));
