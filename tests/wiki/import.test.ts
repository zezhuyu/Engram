test('wiki import handles missing and malformed frontmatter without losing source text', async t => {
  const { vault } = await disposableVault(t); const fixture = await fs.mkdtemp(path.join(os.tmpdir(), 'engram-wiki-frontmatter-'));
  t.after(() => fs.rm(fixture, { recursive: true, force: true }));
  await fs.writeFile(path.join(fixture, 'plain.md'), '# Plain title\nBody');
  await fs.writeFile(path.join(fixture, 'bad.md'), '---\na: [bad\n---\nBad');
  const result = await wikiImport(vault, { from: fixture, workspace: 'frontmatter' });
  assert.equal(result.pages.imported, 2); assert.equal(result.pages.errors.length, 0); assert.equal(result.pages.warnings.length, 1);
  const docs = await vault.listDocuments({ scopes: [{ type: 'workspace', workspaceId: 'frontmatter' }] });
  const doc = docs.find(d => d.metadata.importPath === 'plain.md')!;
  assert.equal(doc.title, 'Plain title'); assert.equal(doc.body, '# Plain title\nBody');
  const malformed = docs.find(d => d.metadata.importPath === 'bad.md')!;
  assert.equal(malformed.title, 'bad'); assert.equal(malformed.body, '---\na: [bad\n---\nBad');
  assert.equal(malformed.tags.includes('unparsed-frontmatter'), true);
  assert.equal(typeof malformed.metadata.frontmatterError, 'string');
  assert.equal(malformed.metadata.rawFrontmatter, 'a: [bad');
});

test('wiki import resolves project-root links, aliases, anchors, embeds, shortest paths and titles; relinks idempotently', async t => {
  const { vault } = await disposableVault(t); const fixture = await fs.mkdtemp(path.join(os.tmpdir(), 'engram-wiki-links-'));
  t.after(() => fs.rm(fixture, { recursive: true, force: true }));
  const wiki = path.join(fixture, 'wiki'), concepts = path.join(wiki, 'pages', 'concepts');
  await fs.mkdir(concepts, { recursive: true });
  await fs.writeFile(path.join(concepts, 'x.md'), '---\ntitle: Concept X\n---\n# X');
  await fs.writeFile(path.join(wiki, 'pages', 'unique.md'), '---\ntitle: Unique Title\n---\nUnique');
  await fs.writeFile(path.join(wiki, 'pages', 'dup-a.md'), '---\ntitle: Duplicate\n---\nA');
  await fs.writeFile(path.join(wiki, 'pages', 'dup-b.md'), '---\ntitle: Duplicate\n---\nB');
  const linkedText = '[[wiki/pages/concepts/x|Display Title]] [[wiki/pages/concepts/x.md#part|Anchor alias]] [[x]] [[Unique Title]] ![[pages/concepts/x#heading]] [[wiki/pages/<subdir>/x|Template]] [[wikilink]] [[Duplicate]]';
  await fs.writeFile(path.join(wiki, 'pages', 'links.md'), linkedText);
  const options = { from: wiki, workspace: 'link-workspace' };
  const beforeDryRun = (await vault.events()).length;
  const dry = await wikiImport(vault, { ...options, dryRun: true });
  assert.equal(dry.wikiLinks.resolved, 5);
  assert.equal((await vault.events()).length, beforeDryRun);
  const first = await wikiImport(vault, { ...options, limitedWikiLinks: true });
  assert.equal(first.wikiLinks.resolved, 3); // Project-root paths and embeds resolve even with the limited resolver.
  assert.equal(first.wikiLinks.placeholders, 2);
  assert.equal(first.wikiLinks.ambiguous, 0);
  const linksDoc = (await vault.listDocuments({ scopes: [{ type: 'workspace', workspaceId: 'link-workspace' }] })).find(d => d.metadata.importPath === 'pages/links.md')!;
  const before = (await vault.history(linksDoc.id)).length;
  const improved = await wikiImport(vault, options);
  assert.equal(improved.pages.relinked, 1);
  assert.equal(improved.wikiLinks.resolved, 5);
  assert.equal(improved.wikiLinks.ambiguous, 1);
  assert.equal(improved.wikiLinks.placeholders, 2);
  const after = await vault.history(linksDoc.id);
  assert.equal(after.length, before + 1);
  const final = await wikiImport(vault, options);
  assert.equal(final.pages.relinked, 0);
  assert.equal((await vault.history(linksDoc.id)).length, after.length);
  const beforeVerify = (await vault.events()).length;
  const verify = await wikiImport(vault, { ...options, verify: true, limitedWikiLinks: true });
  assert.equal(verify.pages['stale-links'].length, 1);
  assert.equal((await vault.events()).length, beforeVerify);
});

test('wiki links to imported raw sources become references and relink once the source is imported', async t => {
  const { vault } = await disposableVault(t); const fixture = await fs.mkdtemp(path.join(os.tmpdir(), 'engram-wiki-raw-links-'));
  t.after(() => fs.rm(fixture, { recursive: true, force: true }));
  const wiki = path.join(fixture, 'wiki'), raw = path.join(fixture, 'raw');
  await fs.mkdir(wiki); await fs.mkdir(raw);
  await fs.writeFile(path.join(wiki, 'missing.md'), '# Missing source name\nThis is a page, not a raw source.');
  const page = `---\ntitle: Source links\nsources: [raw/x.md]\n---\n[[raw/x]] [[raw/x|alias]] ![[raw/x.md]] [[${path.basename(fixture)}/raw/x#heading|project alias]] [[raw/missing]] [[missing-page]]`;
  await fs.writeFile(path.join(wiki, 'page.md'), page);
  const options = { from: wiki, raw, workspace: 'raw-link-workspace' };
  const first = await wikiImport(vault, options);
  assert.equal(first.wikiLinks.resolved, 0);
  assert.deepEqual((first.wikiLinks.unresolved as Array<{ reason: string }>).map(link => link.reason), ['source-not-imported', 'source-not-imported', 'source-not-imported', 'source-not-imported', 'source-not-imported', 'unresolved']);
  await fs.writeFile(path.join(raw, 'x.md'), 'source bytes');
  const second = await wikiImport(vault, options);
  assert.equal(second.sources.imported, 1);
  assert.equal(second.wikiLinks.resolved, 4);
  assert.deepEqual((second.wikiLinks.unresolved as Array<{ reason: string }>).map(link => link.reason), ['source-not-imported', 'unresolved']);
  assert.equal(second.pages.relinked, 1);
  const docs = await vault.listDocuments({ scopes: [{ type: 'workspace', workspaceId: options.workspace }] });
  const importedPage = docs.find(doc => doc.metadata.importPath === 'page.md')!;
  const source = docs.find(doc => doc.metadata.importPath === 'x.md')!;
  const relations = (importedPage.links as Array<{ target: string; type: string }>).filter(link => link.target === source.uri);
  assert.equal(relations.length, 1);
  assert.equal(relations[0]?.type, 'references');
  const revisionCount = (await vault.history(importedPage.id)).length;
  const third = await wikiImport(vault, options);
  assert.equal(third.pages.relinked, 0);
  assert.equal((await vault.history(importedPage.id)).length, revisionCount);
});
