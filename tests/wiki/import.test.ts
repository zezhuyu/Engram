  const badWiki = path.join(fixture, 'bad-global-wiki'), badRaw = path.join(fixture, 'bad-global-raw'), priorWiki = path.join(fixture, 'bad-prior-wiki'), priorRaw = path.join(fixture, 'bad-prior-raw');
