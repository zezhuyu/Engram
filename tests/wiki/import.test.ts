const sha = (data: Uint8Array) => createHash('sha256').update(data).digest('hex');

test('wiki import preserves sources and page originals, resumes without revisions, and verifies read-only', async t => {
  const { root, vault } = await disposableVault(t);
  const fixture = await fs.mkdtemp(path.join(os.tmpdir(), 'engram-wiki-fixture-'));
  t.after(() => fs.rm(fixture, { recursive: true, force: true }));
  const wiki = path.join(fixture, 'wiki'), raw = path.join(fixture, 'raw');
  await fs.mkdir(path.join(wiki, 'pages'), { recursive: true }); await fs.mkdir(path.join(wiki, 'templates')); await fs.mkdir(path.join(raw, 'one'), { recursive: true }); await fs.mkdir(path.join(raw, 'two'));
  const sourceBytes = Buffer.from('original source bytes\r\n');
  await fs.writeFile(path.join(raw, 'one', 'same.md'), sourceBytes); await fs.writeFile(path.join(raw, 'two', 'same.md'), 'different source');
  await fs.writeFile(path.join(raw, 'binary.bin'), Buffer.from([0, 255, 1]));
  await fs.symlink(path.join(raw, 'one', 'same.md'), path.join(raw, 'linked.md'));
  const pageText = '---\ntitle: A page\ntags: one, two\nsources:\n  - raw/one/same.md\ncustom: value\n---\n# A page\n\nSee [[Other]].';
  await fs.writeFile(path.join(wiki, 'pages', 'a.md'), pageText);
  await fs.writeFile(path.join(wiki, 'pages', 'b.md'), '---\ntitle: Other\n---\nSecond page.');
  await fs.writeFile(path.join(wiki, 'templates', 'stub.md'), '# Template\n');
  const options = { from: wiki, raw, workspace: 'migrated', label: 'fixture' };
  const dryBefore = (await vault.events()).length;
  const dry = await wikiImport(vault, { ...options, dryRun: true });
  assert.equal((await vault.events()).length, dryBefore); assert.equal(dry.sources.skipped.length, 1);
  const first = await wikiImport(vault, options);
  assert.equal(first.sources.imported, 3); assert.equal(first.pages.imported, 3);
  assert.equal(first.citations.resolved, 1); assert.equal(first.wikiLinks.resolved, 1);
  const docs = await vault.listDocuments({ scopes: [{ type: 'workspace', workspaceId: 'migrated' }] });
  const a = docs.find(d => d.metadata.importPath === 'pages/a.md')!;
  assert.equal(a.body, pageText); assert.deepEqual(a.metadata.originalFrontmatter, { title: 'A page', tags: 'one, two', sources: ['raw/one/same.md'], custom: 'value' });
  assert.equal(docs.find(d => d.metadata.importPath === 'templates/stub.md')?.tags.includes('template'), true);
  const originals = docs.filter(d => d.kind === 'source');
  assert.equal(originals.length, 3);
  const storedSource = originals.find(d => d.metadata.importPath === 'one/same.md')!;
  assert.equal(sha(await fs.readFile(path.join(root, String(storedSource.metadata.originalPath)))), sha(sourceBytes));
  const linked = await vault.get(a.id); assert.ok(linked.links.some(l => l.type === 'wiki_link'));
  assert.ok(linked.links.some(l => l.type === 'references'));
  const revsBefore = (await vault.history(a.id)).length;
  const second = await wikiImport(vault, options);
  assert.equal(second.pages.unchanged, 3); assert.equal(second.sources.unchanged, 3);
  assert.equal((await vault.history(a.id)).length, revsBefore);
  await fs.writeFile(path.join(wiki, 'pages', 'a.md'), pageText + '\nChanged.');
  const third = await wikiImport(vault, options); assert.equal(third.pages.updated, 1);
  assert.equal((await vault.history(a.id)).length, revsBefore + 1);
  const verify = await wikiImport(vault, { ...options, verify: true }); assert.deepEqual(verify.pages.errors, []); assert.equal(verify.pages.unchanged, 3); assert.equal(verify.sources.unchanged, 3);
  await fs.writeFile(path.join(raw, 'one', 'same.md'), 'modified');
  const mismatch = await wikiImport(vault, { ...options, verify: true }); assert.ok(mismatch.sources.errors.length > 0);
  const outsider = new Vault(root, { actorId: 'outsider', permissions: [] });
  await assert.rejects(wikiImport(outsider, options));
  await assert.rejects(outsider.get(a.id));
});

